function parseYoc(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const labeled = raw.match(/YOC\s*[-:]?\s*(\d+\.?\d*)\s*%/i);
  if (labeled) return `${parseFloat(labeled[1]).toFixed(1)}%`;
  const plain = raw.match(/(\d+\.?\d*)\s*%/);
  if (plain) return `${parseFloat(plain[1]).toFixed(1)}%`;
  return null;
}

function getMemoUrl(deal: Deal): string | null {
  // Investment memo generated by analyst (stored in object storage, served via broker proxy)
  if (deal.investment_memo_url) return `/api/broker-portal/deals/${deal.id}/memo`;
  return null;
}

function formatProductType(raw: string): string {
  const lower = raw.toLowerCase();
  if (lower.startsWith("btr-th") || lower.includes("btr-town") || lower.includes("btr_th")) return "BTR TH";
  if (lower.startsWith("btr-sf") || lower.includes("btr-single") || lower.includes("btr_sf")) return "BTR SF";
  if (lower.startsWith("btr")) return "BTR TH"; // fallback for any other BTR
  return raw
    .replace(/-/g, " ")
    .replace(/\b\w/g, c => c.toUpperCase());
}

