function PortalView({ account }: { account: BrokerAccount }) {
  const [search, setSearch] = useState("");
  const [selectedDeal, setSelectedDeal] = useState<Deal | null>(null);
  const [stateFilter, setStateFilter] = useState("all");
  const [typeFilter, setTypeFilter] = useState("all");
  const [productTypeFilter, setProductTypeFilter] = useState("all");
  const [sortBy, setSortBy] = useState("newest");
  const [showProfile, setShowProfile] = useState(false);

  const logoutMutation = useMutation({
    mutationFn: () => apiRequest("POST", "/api/broker-portal/logout"),
    onSuccess: () => {
      window.location.href = "/broker-portal";
    },
  });

  const { data: deals = [], isLoading, error: dealsError } = useQuery<Deal[]>({
    queryKey: ["/api/broker-portal/deals"],
    retry: 1,
    staleTime: 0,
  });

  const uniqueStates = Array.from(new Set(deals.map(d => d.state).filter(Boolean))) as string[];

  const uniqueProductTypes = Array.from(new Set(
    deals.flatMap(d => {
      const arr: string[] = Array.isArray(d.product_types)
        ? d.product_types
        : (typeof d.product_types === "string" ? (() => { try { return JSON.parse(d.product_types!); } catch { return []; } })() : []);
      return arr;
    })
  )).sort() as string[];

  const filtered = deals
    .filter(d => {
      const q = search.toLowerCase();
      const matchesSearch = !q || (
        (d.address || "").toLowerCase().includes(q) ||
        (d.city || "").toLowerCase().includes(q) ||
        (d.state || "").toLowerCase().includes(q) ||
        (d.property_name || "").toLowerCase().includes(q)
      );
      const matchesState = stateFilter === "all" || d.state === stateFilter;
      const matchesType = typeFilter === "all" || (d.deal_type || "").toLowerCase() === typeFilter;
      const matchesProductType = productTypeFilter === "all" || (() => {
        const arr: string[] = Array.isArray(d.product_types)
          ? d.product_types
          : (typeof d.product_types === "string" ? (() => { try { return JSON.parse(d.product_types!); } catch { return []; } })() : []);
        return arr.includes(productTypeFilter);
      })();
      return matchesSearch && matchesState && matchesType && matchesProductType;
    })
    .sort((a, b) => {
      if (sortBy === "yoc_desc") {
        const aYoc = parseYoc(a.yield_on_cost);
        const bYoc = parseYoc(b.yield_on_cost);
        const aNum = aYoc ? parseFloat(aYoc) : -Infinity;
        const bNum = bYoc ? parseFloat(bYoc) : -Infinity;
        return bNum - aNum;
      }
      if (sortBy === "rent_desc") {
        const aRent = a.top_rent_psf ? parseFloat(a.top_rent_psf) : -Infinity;
        const bRent = b.top_rent_psf ? parseFloat(b.top_rent_psf) : -Infinity;
        return bRent - aRent;
      }
      if (sortBy === "price_asc") {
        const aP = a.asking_price ? parseInt(a.asking_price) : Infinity;
        const bP = b.asking_price ? parseInt(b.asking_price) : Infinity;
        return aP - bP;
      }
      if (sortBy === "price_desc") {
        const aP = a.asking_price ? parseInt(a.asking_price) : -Infinity;
        const bP = b.asking_price ? parseInt(b.asking_price) : -Infinity;
        return bP - aP;
      }
      if (sortBy === "acres_desc") {
        const aA = a.size_acres ? parseFloat(a.size_acres) : -Infinity;
        const bA = b.size_acres ? parseFloat(b.size_acres) : -Infinity;
        return bA - aA;
      }
      if (sortBy === "units_desc") {
        const aU = a.unit_count || -Infinity;
        const bU = b.unit_count || -Infinity;
        return (bU as number) - (aU as number);
      }
      // newest (default)
      return new Date(b.created_at).getTime() - new Date(a.created_at).getTime();
    });

  return (
    <div className="min-h-screen bg-gray-50 flex flex-col">
      {/* Header — matches main site style */}
      <header className="bg-[#081729] text-white sticky top-0 z-40 shadow-md">
        <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-3 flex items-center justify-between gap-4">
          {/* Logo */}
          <a href="/" className="flex items-center gap-2 shrink-0">
            <div className="overflow-hidden flex-shrink-0" style={{ width: 36, height: 26 }}>
              <img src={landlinqLogo} alt="" style={{ height: 26, width: "auto", maxWidth: "none" }} />
            </div>
            <span className="font-bold text-base tracking-tight leading-none">LandLinq</span>
            <span className="hidden sm:inline text-[#94a3b8] text-xs ml-1 font-normal">· Partner Broker Portal</span>
          </a>

          {/* Right side */}
          <div className="flex items-center gap-3">
            <button
              onClick={() => setShowProfile(true)}
              className="hidden sm:flex items-center gap-1.5 text-xs text-[#94a3b8] hover:text-white transition-colors px-3 py-1.5 rounded-lg hover:bg-white/10"
            >
              <Settings className="w-3.5 h-3.5" />
              Edit Profile
            </button>
            <div className="hidden sm:block text-right">
              <div className="text-sm font-medium">{account.firstName} {account.lastName}</div>
              {account.brokerage && <div className="text-[11px] text-[#94a3b8]">{account.brokerage}</div>}
            </div>
            <button
              onClick={() => logoutMutation.mutate()}
              className="flex items-center gap-1.5 text-xs text-[#94a3b8] hover:text-white transition-colors px-3 py-1.5 rounded-lg hover:bg-white/10"
            >
              <LogOut className="w-3.5 h-3.5" /> Sign Out
            </button>
          </div>
        </div>
      </header>

      {/* Market summary bar */}
      {(account.targetStates.length > 0 || account.targetMsas.length > 0 || account.targetCities.length > 0) && (
        <div className="bg-white border-b border-gray-200">
          <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-2.5 flex items-center gap-2 flex-wrap">
            <span className="text-xs text-gray-500 font-medium shrink-0">Your Markets:</span>
            {account.targetStates.map(s => (
              <span key={s} className="text-[10px] bg-[#0d2d4e]/10 text-[#0d2d4e] px-2 py-0.5 rounded-full font-medium">{s}</span>
            ))}
            {account.targetMsas.map(m => (
              <span key={m} className="text-[10px] bg-blue-100 text-blue-700 px-2 py-0.5 rounded-full font-medium">{m}</span>
            ))}
            {account.targetCities.map(c => (
              <span key={c} className="text-[10px] bg-purple-100 text-purple-700 px-2 py-0.5 rounded-full font-medium">{c}</span>
            ))}
            <button
              onClick={() => setShowProfile(true)}
              className="text-[10px] text-[#0d2d4e] hover:underline font-medium ml-1"
            >
              Edit →
            </button>
          </div>
        </div>
      )}

      {/* Main content */}
      <div className="flex-1 max-w-7xl mx-auto w-full px-4 sm:px-6 lg:px-8 py-6">
        <div className="flex items-center justify-between gap-4 mb-5 flex-wrap">
          <div>
            <h1 className="text-xl font-bold text-[#0d2d4e]">Available Deals</h1>
            <p className="text-sm text-gray-500 mt-0.5">{filtered.length} deal{filtered.length !== 1 ? "s" : ""} in your markets</p>
          </div>
          <div className="flex items-center gap-2 flex-wrap">
            <button
              onClick={() => setShowProfile(true)}
              className="sm:hidden flex items-center gap-1.5 text-xs border border-gray-200 rounded-lg px-3 py-1.5 text-gray-600 hover:bg-gray-50"
            >
              <Pencil className="w-3.5 h-3.5" /> Edit Profile
            </button>
            {/* Deal type toggle */}
            <div className="flex items-center rounded-lg border border-gray-200 bg-white overflow-hidden">
              {[
                { value: "all",         label: "All Types" },
                { value: "land",        label: "Land" },
                { value: "acquisition", label: "Acquisition" },
              ].map(opt => (
                <button
                  key={opt.value}
                  onClick={() => setTypeFilter(opt.value)}
                  className={`text-xs px-3 py-1.5 font-medium transition-colors border-r last:border-r-0 border-gray-200 ${
                    typeFilter === opt.value
                      ? "bg-[#0d2d4e] text-white"
                      : "text-gray-600 hover:bg-gray-50"
                  }`}
                >
                  {opt.label}
                </button>
              ))}
            </div>
            {uniqueStates.length > 1 && (
              <select
                value={stateFilter}
                onChange={e => setStateFilter(e.target.value)}
                className="text-sm border border-gray-200 rounded-lg px-3 py-1.5 bg-white focus:outline-none focus:ring-2 focus:ring-[#0d2d4e]/20"
              >
                <option value="all">All States</option>
                {uniqueStates.sort().map(s => (
                  <option key={s} value={s}>{s}</option>
                ))}
              </select>
            )}
            {uniqueProductTypes.length > 0 && (
              <select
                value={productTypeFilter}
                onChange={e => setProductTypeFilter(e.target.value)}
                className="text-sm border border-gray-200 rounded-lg px-3 py-1.5 bg-white focus:outline-none focus:ring-2 focus:ring-[#0d2d4e]/20"
              >
                <option value="all">All Product Types</option>
                {uniqueProductTypes.map(t => (
                  <option key={t} value={t}>{formatProductType(t)}</option>
                ))}
              </select>
            )}
            <select
              value={sortBy}
              onChange={e => setSortBy(e.target.value)}
              className="text-sm border border-gray-200 rounded-lg px-3 py-1.5 bg-white focus:outline-none focus:ring-2 focus:ring-[#0d2d4e]/20"
            >
              <option value="newest">Newest First</option>
              <option value="yoc_desc">Highest YOC</option>
              <option value="rent_desc">Highest Mkt Rent</option>
              <option value="price_asc">Price: Low → High</option>
              <option value="price_desc">Price: High → Low</option>
              <option value="acres_desc">Largest Acreage</option>
              <option value="units_desc">Most Units</option>
            </select>
            <div className="relative">
              <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-gray-400" />
              <Input
                value={search}
                onChange={e => setSearch(e.target.value)}
                placeholder="Search deals…"
                className="pl-9 h-9 text-sm w-44"
              />
            </div>
          </div>
        </div>

        {isLoading ? (
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
            {[1,2,3,4,5,6].map(i => (
              <div key={i} className="bg-white border border-gray-200 rounded-xl p-5 animate-pulse">
                <div className="h-3 bg-gray-200 rounded w-1/3 mb-3" />
                <div className="h-4 bg-gray-200 rounded w-3/4 mb-2" />
                <div className="h-3 bg-gray-200 rounded w-1/2" />
              </div>
            ))}
          </div>
        ) : dealsError ? (
          <div className="text-center py-20">
            <Building2 className="w-12 h-12 mx-auto mb-3 text-red-300" />
            <p className="font-medium text-red-600 mb-1">Unable to load deals</p>
            <p className="text-sm text-gray-500">{String((dealsError as any)?.message || dealsError)}</p>
          </div>
        ) : filtered.length === 0 ? (
          <div className="text-center py-20 text-gray-400">
            <Building2 className="w-12 h-12 mx-auto mb-3 text-gray-200" />
            <p className="font-medium text-gray-500 mb-1">No deals found</p>
            <p className="text-sm">
              {deals.length === 0
                ? "No deals are currently available in your markets."
                : "Try adjusting your search or filter."}
            </p>
            {deals.length === 0 && (
              <button onClick={() => setShowProfile(true)} className="mt-4 text-sm text-[#0d2d4e] underline">
                Update your market criteria
              </button>
            )}
          </div>
        ) : (
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
            {filtered.map(deal => (
              <DealCard key={deal.id} deal={deal} onClick={() => setSelectedDeal(deal)} />
            ))}
          </div>
        )}
      </div>

      <Footer />

      {selectedDeal && <DealDetailModal deal={selectedDeal} onClose={() => setSelectedDeal(null)} />}
      {showProfile && <ProfileModal account={account} onClose={() => setShowProfile(false)} />}
    </div>
  );
}

export default function BrokerPortal() {
  const [loggedIn, setLoggedIn] = useState(false);

  const { data: account, isLoading } = useQuery<BrokerAccount>({
    queryKey: ["/api/broker-portal/me"],
    retry: false,
  });

  if (isLoading) {
    return (
      <div className="min-h-screen bg-gradient-to-br from-[#081729] to-[#0d2d4e] flex items-center justify-center">
        <div className="text-white text-sm">Loading…</div>
      </div>
    );
  }

  if (!account) {
    return <LoginView onLogin={() => setLoggedIn(true)} />;
  }

  return <PortalView account={account} />;
}
